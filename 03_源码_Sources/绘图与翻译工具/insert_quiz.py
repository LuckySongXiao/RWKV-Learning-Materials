def insert_quiz(path):
    lines = open(path, encoding='utf-8').read().split('\n')
    out, chapter, last_content_idx = [], None, -1
    for i, line in enumerate(lines):
        m = re.match(r'\s*\{ h2: "(第 \d+ 章[^"]*)"', line)
        if m:
            # 在上一章的最后内容块后插入 quiz
            if chapter in QUIZ and last_content_idx >= 0:
                q = QUIZ[chapter]
                block = ',\n'.join([f'    "{item}"' for item in q])
                out.insert(last_content_idx + 1, f'  {{ quiz: [\n{block}\n  ]}},')
            chapter = m.group(1).split('：')[0].split(' ')[0] + ' ' + m.group(1).split(' ')[1] if '：' in m.group(1) else None
            # 更稳健：直接取 "第 N 章"
            chapter = re.match(r'(第 \d+ 章)', m.group(1)).group(1) if re.match(r'(第 \d+ 章)', m.group(1)) else None
        out.append(line)
        if line.strip().startswith('{') and not line.strip().startswith('{ h2') and not line.strip().startswith('{ quiz'):
            last_content_idx = len(out) - 1
    # 文件末尾（第 17 章在 part345 中间，实际由中间 h2 触发）
    open(path, 'w', encoding='utf-8').write('\n'.join(out))
    return chapter

